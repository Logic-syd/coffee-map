export type TranslationKey = keyof typeof translations;
export function t(key: TranslationKey, locale: Language = "en"): string {
  const translation = translations[key];
  return translation?.[locale]?.trim() || translation?.["zh-CN"]?.trim() || key;
}
export function venueName(
  name: { zh?: string; en?: string; ja?: string; ko?: string } | undefined,
  locale: Language,
): string {
  const key = locale === "zh-CN" ? "zh" : locale;
  return (
    [name?.[key], name?.zh, name?.en, name?.ja, name?.ko]
      .find((value) => value?.trim())
      ?.trim() || t("venue.unnamed", locale)
  );
}
export function formatDistance(distanceKm: number, locale: Language): string {
  const meters = distanceKm < 1;
  const value = meters ? Math.round((distanceKm * 1000) / 10) * 10 : distanceKm;
  return new Intl.NumberFormat(locale, {
    style: "unit",
    unit: meters ? "meter" : "kilometer",
    unitDisplay: "short",
    maximumFractionDigits: meters ? 0 : 1,
  }).format(value);
}
export function formatHours(
  start: string,
  end: string,
  locale: Language,
): string {
  return `${start}–${end}${end < start ? ` (${t("hours.nextDay", locale)})` : ""}`;
}
